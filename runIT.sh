#!/usr/bin/env bash

set -Eeuo pipefail

ROOT_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
cd "$ROOT_DIR"

usage() {
  cat <<'EOF'
Usage: ./runIT.sh [--prepare-only]

Prepare private local keys and start the Compose stack. The stack publishes
its gateway, Admin API, and metrics ports on localhost only.

Options:
  --prepare-only  Generate .env without starting containers.
  -h, --help      Show this help.
EOF
}

PREPARE_ONLY=false
case "${1:-}" in
  "") ;;
  --prepare-only) PREPARE_ONLY=true ;;
  -h|--help) usage; exit 0 ;;
  *) usage >&2; exit 2 ;;
esac

if ! command -v openssl >/dev/null 2>&1; then
  printf 'Required command not found: openssl\n' >&2
  exit 1
fi

if [[ ! -f .env ]]; then
  umask 077
  env_tmp="$(mktemp .env.XXXXXX)"
  trap 'rm -f -- "${env_tmp:-}"' EXIT
  {
    printf '# Local secrets generated by runIT.sh. Do not commit this file.\n'
    printf 'APISIX_ADMIN_KEY=%s\n' "$(openssl rand -hex 32)"
    printf 'APISIX_VIEWER_KEY=%s\n' "$(openssl rand -hex 32)"
    printf 'APISIX_IMAGE_TAG=3.19.0-debian\n'
    printf 'APISIX_HTTP_PORT=8080\n'
    printf 'APISIX_HTTPS_PORT=8443\n'
    printf 'APISIX_ADMIN_PORT=9180\n'
    printf 'APISIX_METRICS_PORT=9091\n'
  } > "$env_tmp"
  chmod 600 "$env_tmp"
  mv -- "$env_tmp" .env
  trap - EXIT
  printf 'Created .env with unique local API keys. Secret values were not displayed.\n'
fi

chmod 600 .env

load_env_file() {
  local line key value
  local -A seen_keys=()
  while IFS= read -r line || [[ -n "$line" ]]; do
    line="${line%$'\r'}"
    [[ "$line" =~ ^[[:space:]]*(#.*)?$ ]] && continue
    if [[ "$line" != *=* ]]; then
      printf 'Invalid .env entry; expected KEY=value.\n' >&2
      return 1
    fi
    key="${line%%=*}"
    value="${line#*=}"
    if [[ ! "$key" =~ ^[A-Z_][A-Z0-9_]*$ ]]; then
      printf 'Invalid .env variable name.\n' >&2
      return 1
    fi
    if [[ -n "${seen_keys[$key]:-}" ]]; then
      printf 'Duplicate .env variable: %s\n' "$key" >&2
      return 1
    fi
    seen_keys["$key"]=1
    case "$key" in
      APISIX_ADMIN_KEY|APISIX_VIEWER_KEY)
        if [[ ! "$value" =~ ^[A-Fa-f0-9]{64}$ ]]; then
          printf '%s must be a 64-character hexadecimal secret.\n' "$key" >&2
          return 1
        fi
        ;;
      APISIX_IMAGE_TAG)
        if [[ ! "$value" =~ ^[A-Za-z0-9_.-]+$ ]]; then
          printf 'APISIX_IMAGE_TAG contains unsupported characters.\n' >&2
          return 1
        fi
        ;;
      APISIX_HTTP_PORT|APISIX_HTTPS_PORT|APISIX_ADMIN_PORT|APISIX_METRICS_PORT)
        if [[ ! "$value" =~ ^[0-9]{4,5}$ ]] || (( 10#$value < 1024 || 10#$value > 65535 )); then
          printf '%s must be a TCP port from 1024 to 65535.\n' "$key" >&2
          return 1
        fi
        ;;
      *)
        printf 'Unsupported .env variable: %s\n' "$key" >&2
        return 1
        ;;
    esac
    export "$key=$value"
  done < .env
}

load_env_file

for key_name in APISIX_ADMIN_KEY APISIX_VIEWER_KEY; do
  if [[ -z "${!key_name:-}" ]]; then
    printf 'Missing required value for %s in .env.\n' "$key_name" >&2
    exit 1
  fi
done
if [[ "$APISIX_ADMIN_KEY" == "$APISIX_VIEWER_KEY" ]]; then
  printf 'APISIX_ADMIN_KEY and APISIX_VIEWER_KEY must be different.\n' >&2
  exit 1
fi

if [[ "$PREPARE_ONLY" == true ]]; then
  printf 'Local secrets are ready; APISIX resolves them from its environment.\n'
  exit 0
fi

if ! command -v docker >/dev/null 2>&1 || ! docker compose version >/dev/null 2>&1; then
  printf 'Docker Engine with Docker Compose v2 is required to start the stack.\n' >&2
  exit 1
fi

docker compose up --detach --remove-orphans

printf '\nAPISIX is starting. Local endpoints:\n'
printf '  Gateway:    http://127.0.0.1:%s/\n' "${APISIX_HTTP_PORT:-8080}"
printf '  Dashboard:  http://127.0.0.1:%s/ui/\n' "${APISIX_ADMIN_PORT:-9180}"
printf '  Admin API:  http://127.0.0.1:%s/apisix/admin/routes\n' "${APISIX_ADMIN_PORT:-9180}"
printf '  Prometheus: http://127.0.0.1:%s/apisix/prometheus/metrics\n' "${APISIX_METRICS_PORT:-9091}"
printf '\nThe Admin API key is stored in .env and was not printed. This Compose setup is\n'
printf 'for local evaluation; it is not a production deployment configuration.\n'
